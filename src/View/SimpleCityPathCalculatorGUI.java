    private void updateButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_updateButtonActionPerformed
        try {
            double newAutonomy = Double.parseDouble(autonomyField.getText().trim());
            cities.setAuxDistance(newAutonomy); // Atualiza a autonomia na classe Cities
            updateAutonomyField(); // Atualiza o campo de texto (se necessário)
            JOptionPane.showMessageDialog(this, "Autonomy updated to " + newAutonomy + " km!");
        } catch (NumberFormatException ex) {
            JOptionPane.showMessageDialog(this, "Please enter a valid number.", "Error", JOptionPane.ERROR_MESSAGE);
        } catch (Exception ex) {
            JOptionPane.showMessageDialog(this, "Error updating autonomy: " + ex.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
        }

    }//GEN-LAST:event_updateButtonActionPerformed

