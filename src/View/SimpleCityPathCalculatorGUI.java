    private void calculateButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_calculateButtonActionPerformed
        String sourceName = sourceField.getText().trim();
        String destinationName = destinationField.getText().trim();

        if (sourceName.isEmpty() || destinationName.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please, insert both origin and destination city");
            return;
        }

        try {
            int source = cities.getCity(sourceName);
            int destination = cities.getCity(destinationName);

            if (source == -1 || destination == -1) {
                JOptionPane.showMessageDialog(this, "Error: City not found");
                return;
            }

            DijkstraAlgorithm dijkstra = new DijkstraAlgorithm(cities.getNumberCity(), cities.getGraph(), cities.getCities());
            dijkstra.dijkstra(source);

            // Exibir o resultado
            resultArea.setText(dijkstra.getShortestPathDetails(destination));
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error calculating path: " + e.getMessage());
        }
    }//GEN-LAST:event_calculateButtonActionPerformed

